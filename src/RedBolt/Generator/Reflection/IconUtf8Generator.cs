namespace RedBolt.Generator.Reflection;

using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

[Generator]
public sealed class IconUtf8Generator : IIncrementalGenerator
{
    private const string IconsTypeName = "RedBolt.Utility.Icons";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var iconsTypes = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { Identifier.ValueText: "Icons" },
                static (syntaxContext, _) => GetIconsType(syntaxContext))
            .Where(static type => type is not null)
            .Collect();

        context.RegisterSourceOutput(iconsTypes, Execute);
    }

    private static INamedTypeSymbol? GetIconsType(GeneratorSyntaxContext context)
    {
        var type = context.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)context.Node);
        return type?.ToDisplayString() == IconsTypeName ? type : null;
    }

    private static void Execute(
        SourceProductionContext context, ImmutableArray<INamedTypeSymbol?> types)
    {
        var type = types.FirstOrDefault();
        if (type is null)
            return;

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("namespace RedBolt.Utility;");
        builder.AppendLine();
        builder.AppendLine("public partial class Icons");
        builder.AppendLine("{");

        foreach (var field in type.GetMembers().OfType<IFieldSymbol>()
                     .Where(static field => field is { IsConst: true, ConstantValue: string })
                     .OrderBy(static field => field.Locations.FirstOrDefault()?.SourceSpan.Start ?? 0))
        {
            var value = SymbolDisplay.FormatLiteral((string)field.ConstantValue!, true);
            builder.Append("    public static global::System.ReadOnlySpan<byte> ")
                .Append(field.Name)
                .Append("U8 => ")
                .Append(value)
                .AppendLine("u8;");
        }

        builder.AppendLine("}");
        context.AddSource("RedBolt.Utility.Icons.Utf8.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }
}
