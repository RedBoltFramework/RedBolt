namespace RedBolt.Utility;

public static class AnimationMetadata
{
    /// <summary>Resource name of the Model that is meant to be used with this Animation.</summary>
    public const string Model = "Model";
    /// <summary>Whether the Animation is looped.</summary>
    public const string Looped = "Looped";
    /// <summary>Frame step of fixed-rate animation, may contain unspecified value for variable-rate animations.</summary>
    public const string FrameStep = "FrameStep";
    /// <summary>Frame rate of fixed-rate animation, may contain unspecified value for variable-rate animations.</summary>
    public const string FrameRate = "FrameRate";
    /// <summary>Map of parent animation tracks for each animation track. Variant tracks are ignored.</summary>
    public const string ParentTracks = "ParentTracks";
    /// <summary>Whitelist of animation tracks to be generated by GenerateWorldSpaceTracksTransformer.</summary>
    public const string IKTargetTracks = "IKTargetTracks";
    /// <summary>Root motion track name.</summary>
    public const string RootTrack = "RootTrack";
    /// <summary>Original root motion backup track name.</summary>
    public const string OriginalRootTrack = "OriginalRootTrack";
    /// <summary>Linear velocity of root motion that was undone.</summary>
    public const string RootLinearVelocity = "RootLinearVelocity";
    /// <summary>Angular velocity of root motion that was undone.</summary>
    public const string RootAngularVelocity = "RootAngularVelocity";
    /// <summary>"Scale velocity" of root motion that was undone.</summary>
    public const string RootScaleVelocity = "RootScaleVelocity";
}
